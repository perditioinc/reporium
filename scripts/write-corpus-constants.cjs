#!/usr/bin/env node
/**
 * Read public/data/library.json and rewrite src/lib/corpusConstants.generated.ts
 * with the current corpus totals so hardcoded marketing/UI copy stays in sync.
 *
 * Runs in prebuild chain: fetch-library -> write-corpus-constants -> sync-data-dir
 */
const fs = require('fs');
const path = require('path');

const LIBRARY = path.join(process.cwd(), 'public', 'data', 'library.json');
const OUT = path.join(process.cwd(), 'src', 'lib', 'corpusConstants.generated.ts');

if (!fs.existsSync(LIBRARY)) {
  console.error(`[corpus-constants] ${LIBRARY} missing — run \`npm run generate\` first`);
  process.exit(1);
}

const lib = JSON.parse(fs.readFileSync(LIBRARY, 'utf-8'));
const reposIndexed = lib.totalRepos ?? lib.repos?.length ?? 0;
const categories = Array.isArray(lib.categories)
  ? lib.categories.length
  : (lib.stats?.categoryCount ?? 16);
// Graph edge types are a product constant (DEPENDS_ON, ALTERNATIVE_TO, EXTENDS,
// SIMILAR_TO, COMPATIBLE_WITH — currently 5 defined, 4 active). Freeze here.
const graphEdgeTypes = 4;

const ts = `// AUTO-GENERATED by scripts/write-corpus-constants.cjs — do not edit by hand.
// Regenerate: \`npm run generate && node scripts/write-corpus-constants.cjs\`
// Runs automatically in prebuild.
export const CORPUS_STATS = {
  reposIndexed: ${reposIndexed},
  categories: ${categories},
  graphEdgeTypes: ${graphEdgeTypes},
} as const;

/** Pre-formatted with thousands separator, e.g. "1,825". */
export const REPOS_INDEXED_LABEL = ${JSON.stringify(reposIndexed.toLocaleString('en-US'))};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, ts);
console.log(`[corpus-constants] wrote ${OUT} (reposIndexed=${reposIndexed}, categories=${categories})`);
